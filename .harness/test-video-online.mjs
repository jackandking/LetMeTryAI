/**
 * Generate video using ONLINE URL
 * 使用在线URL生成视频，确保内容与上线网站一致
 */

import { generateScreenshotVideo } from './src/services/video-screenshot.ts';
import { join } from 'path';
import { existsSync, statSync } from 'fs';
import { spawn } from 'child_process';

const OUTPUT_DIR = join(process.cwd(), '.local', 'video-online');
const EMAIL_TO = 'jackandking@163.com';

// 使用在线URL
const TEST_APP = {
  appId: 'tank-systems-compare',
  appName: '坦克系统对比',
  appUrl: 'https://letmetryai.cn/tank-systems-compare/',
};

async function sendEmail(result) {
  console.log('\n📧 发送邮件...');
  
  const stats = statSync(result.videoPath);
  const sizeMB = (stats.size / 1024 / 1024).toFixed(2);
  
  const content = result.content || {};
  
  const py = `
import subprocess
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.mime.base import MIMEBase
from email import encoders

msg = MIMEMultipart()
msg['From'] = 'harness@letmetryai.cn'
msg['To'] = '${EMAIL_TO}'
msg['Subject'] = '🎬 坦克系统对比 - 在线网站截图版'

body = '''视频已生成！使用在线网站截图。

🔗 在线访问：
https://letmetryai.cn/tank-systems-compare/

✅ 技术栈：
- 截图：Playwright 在线抓取 (375x812 retina)
- 图片：MiniMax image-01 AI生成 (已上线)
- 配音：macOS say (Ting-Ting)
- 合成：ffmpeg (1080x1920 竖屏)

📱 网站内容：
标题: ${content.title || 'N/A'}
问题: ${content.question || 'N/A'}

视频与线上网站完全一致！

文件大小: ${sizeMB} MB

---
Generated by LetMeTryAI Harness
'''
msg.attach(MIMEText(body, 'plain', 'utf-8'))

# Attach video
with open('${result.videoPath}', 'rb') as f:
    att = MIMEBase('application', 'octet-stream')
    att.set_payload(f.read())
encoders.encode_base64(att)
att.add_header('Content-Disposition', 'attachment; filename="tank-online-video.mp4"')
msg.attach(att)

# Attach screenshot
with open('${result.screenshotPath}', 'rb') as f:
    att2 = MIMEBase('image', 'jpeg')
    att2.set_payload(f.read())
encoders.encode_base64(att2)
att2.add_header('Content-Disposition', 'attachment; filename="online-screenshot.jpg"')
msg.attach(att2)

subprocess.run(['/usr/sbin/sendmail', '-t'], input=msg.as_bytes())
print('邮件已发送')
`;
  
  return new Promise((resolve) => {
    spawn('python3', ['-c', py]).on('close', code => {
      console.log(code === 0 ? '✅ 邮件发送成功!' : '❌ 发送失败');
      resolve(code === 0);
    });
  });
}

async function main() {
  console.log('\n🎬 使用在线URL生成视频\n');
  console.log(`应用: ${TEST_APP.appName}`);
  console.log(`URL: ${TEST_APP.appUrl}`);
  console.log(`邮箱: ${EMAIL_TO}\n`);
  
  console.log('⏳ 开始截图（从在线网站）...\n');
  
  try {
    const result = await generateScreenshotVideo({
      appId: TEST_APP.appId,
      appName: TEST_APP.appName,
      appUrl: TEST_APP.appUrl,  // 使用在线URL
      outputDir: OUTPUT_DIR,
      viewport: { width: 375, height: 812 },
    });
    
    console.log('\n═══════════════════════════════════════════════════════════════');
    console.log('✅ 生成结果');
    console.log('═══════════════════════════════════════════════════════════════');
    console.log(`成功: ${result.success ? '✅' : '❌'}`);
    
    if (result.success) {
      console.log(`\n📱 网站内容（在线抓取）:`);
      console.log(`  标题: ${result.content?.title || 'N/A'}`);
      console.log(`  问题: ${result.content?.question || 'N/A'}`);
      
      const stats = statSync(result.videoPath);
      console.log(`\n📹 视频: ${(stats.size / 1024 / 1024).toFixed(2)} MB, ${result.duration?.toFixed(1)}秒`);
      
      await sendEmail(result);
      console.log('\n✅ 完成！视频内容与线上网站一致。\n');
    } else {
      console.log(`\n❌ 错误: ${result.error}`);
    }
    
  } catch (error) {
    console.error('\n❌ 错误:', error.message);
  }
}

main();
